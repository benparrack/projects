def tile_bytes(rows):
    out = []
    for r in rows:
        lo = hi = 0
        for i, ch in enumerate(r):
            v = int(ch)
            lo |= (v & 1) << (7 - i)
            hi |= (v >> 1) << (7 - i)
        out += [lo, hi]
    return out

def glyph_rows(g):
    rows = ['0' + ''.join('3' if c == '#' else '0' for c in r) + '00' for r in g]
    return rows + ['00000000']

def line(label, b):
    return f'    db {", ".join(f"${x:02X}" for x in b)} ; {label}'

out = ['; generated by gfx.py — do not edit', 'GameTiles:']
for i in sorted(TILES):
    out.append(line(f'tile {i}', tile_bytes(TILES[i])))
out.append('.end', )
out.append('Font: ; ASCII $20-$5F, loaded at tile index = character code')
for code in range(0x20, 0x60):
    g = FONT.get(chr(code), FONT[' '])
    out.append(line(repr(chr(code)), tile_bytes(glyph_rows(g))))
out.append('.end')
open('tiles.inc', 'w').write('\n'.join(out) + '\n')
